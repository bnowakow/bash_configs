#!/usr/bin/env bash
# Regenerate inventory/k3s-cluster.ini (used by run-cluster-nodes.sh) from the
# Proxmox host list in nas/ansible/inventory/proxmox-vms.yml, keeping only the
# hosts that are nodes of the running k3s cluster.
#
# A Proxmox host is kept when the first label of its inventory name
# (proxmox3.localdomain.bnowakowski.pl -> proxmox3) equals a Kubernetes node
# name. Groups come from the live cluster:
#   k3s_servers     nodes with the control-plane role
#   k3s_agents      the other nodes
#   longhorn_nodes  nodes that have a Longhorn node object (nodes.longhorn.io)
# k3s nodes that are not in the Proxmox inventory are reported, not added.
#
# Usage:
#   ./sync-k3s-inventory.sh           # write the file, show the diff
#   ./sync-k3s-inventory.sh --check   # only show the diff; exit 1 if out of date

set -Eeuo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd -- "$script_dir/../.." && pwd)"
source_inventory="${PROXMOX_INVENTORY:-$repo_root/nas/ansible/inventory/proxmox-vms.yml}"
target_inventory="$script_dir/inventory/k3s-cluster.ini"
export KUBECONFIG="${KUBECONFIG:-/etc/rancher/k3s/k3s.yaml}"
check_only=0

case "${1:-}" in
  --check) check_only=1 ;;
  -h|--help) sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  "") ;;
  *) echo "Unknown option: $1" >&2; exit 2 ;;
esac

for cmd in ansible kubectl jq; do
  command -v "$cmd" >/dev/null 2>&1 || { echo "$cmd is not installed or not in PATH." >&2; exit 2; }
done
[[ -f "$source_inventory" ]] || { echo "Missing $source_inventory" >&2; exit 2; }

# All hosts of the Proxmox inventory (ansible resolves groups and children).
mapfile -t proxmox_hosts < <(
  ansible -i "$source_inventory" all --list-hosts 2>/dev/null | sed -n 's/^ \{4,\}//p'
)
[[ ${#proxmox_hosts[@]} -gt 0 ]] || { echo "No hosts found in $source_inventory" >&2; exit 2; }

# Live cluster: "name<TAB>is-control-plane".
nodes_json="$(kubectl get nodes -o json)"
mapfile -t k3s_nodes < <(jq -r '.items[] | [.metadata.name,
  (.metadata.labels | has("node-role.kubernetes.io/control-plane"))] | @tsv' <<< "$nodes_json")
mapfile -t longhorn_nodes < <(
  kubectl -n longhorn-system get nodes.longhorn.io -o json 2>/dev/null | jq -r '.items[].metadata.name' || true
)

declare -A fqdn_by_short=()
for host in "${proxmox_hosts[@]}"; do
  fqdn_by_short["${host%%.*}"]="$host"
done

servers=() agents=() longhorn=() missing=()
for line in "${k3s_nodes[@]}"; do
  name="${line%%$'\t'*}"
  control_plane="${line##*$'\t'}"
  if [[ -z "${fqdn_by_short[$name]:-}" ]]; then
    missing+=("$name")
    continue
  fi
  entry="$name ansible_host=${fqdn_by_short[$name]}"
  if [[ "$control_plane" == "true" ]]; then servers+=("$entry"); else agents+=("$entry"); fi
  for l in "${longhorn_nodes[@]}"; do
    [[ "$l" == "$name" ]] && longhorn+=("$name")
  done
done

if [[ ${#servers[@]} -eq 0 ]]; then
  echo "No k3s server node matches a host in $source_inventory; not writing an empty inventory." >&2
  exit 1
fi

new_file="$(mktemp)"
trap 'rm -f "$new_file"' EXIT
{
  cat <<'HEADER'
# The nodes of the running k3s cluster only, for run-cluster-nodes.sh.
# GENERATED by sync-k3s-inventory.sh from nas/ansible/inventory/proxmox-vms.yml,
# filtered to hosts that are current k3s nodes (kubectl get nodes). Re-run the
# script after adding or removing a node instead of editing this file.
# Short names must match the Kubernetes node names and k3s_init_host.
HEADER
  printf '\n[k3s_servers]\n';    printf '%s\n' "${servers[@]}"
  printf '\n[k3s_agents]\n';     [[ ${#agents[@]} -gt 0 ]] && printf '%s\n' "${agents[@]}"
  printf '\n[longhorn_nodes]\n'; [[ ${#longhorn[@]} -gt 0 ]] && printf '%s\n' "${longhorn[@]}"
  printf '\n[all:vars]\nansible_user=sup\nansible_become=true\n'
} > "$new_file"

if [[ ${#missing[@]} -gt 0 ]]; then
  echo "Warning: k3s nodes not in $source_inventory (not added): ${missing[*]}" >&2
fi

if [[ -f "$target_inventory" ]] && diff -q "$target_inventory" "$new_file" >/dev/null; then
  echo "$target_inventory is up to date (${#servers[@]} servers, ${#agents[@]} agents, ${#longhorn[@]} Longhorn nodes)."
  exit 0
fi

if [[ -f "$target_inventory" ]]; then
  diff -u --label "current $target_inventory" --label "new" "$target_inventory" "$new_file" || true
else
  diff -u --label "(missing) $target_inventory" --label "new" /dev/null "$new_file" || true
fi

if [[ "$check_only" -eq 1 ]]; then
  echo "$target_inventory is out of date; run without --check to update it." >&2
  exit 1
fi

install -m 0644 "$new_file" "$target_inventory"
echo "Wrote $target_inventory"
